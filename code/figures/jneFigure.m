function fig = jneFigure(w, h, st)
% jneFigure(w, h, st) — create a white figure of size [w h] inches with the JNE
% style applied as axes/line defaults, so anything drawn inside inherits it.
if nargin < 3 || isempty(st), st = jneStyle(); end
if nargin < 1 || isempty(w), w = st.WidthDouble; end
if nargin < 2 || isempty(h), h = st.RowHeight; end
fig = figure('Color','w', 'Units','inches', 'Position',[1 1 w h], ...
    'DefaultAxesFontName',   st.FontName, ...
    'DefaultAxesFontSize',   st.FontSizeTick, ...
    'DefaultAxesLineWidth',  st.LineWidthAxis, ...
    'DefaultAxesBox',        st.Box, ...
    'DefaultAxesTickDir',    st.TickDir, ...
    'DefaultAxesTickLength', st.TickLength, ...
    'DefaultAxesLayer',      'top', ...
    'DefaultLineLineWidth',  st.LineWidthData);
end
